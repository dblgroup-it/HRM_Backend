const NOW = new Date('2026-09-14T00:00:00.000Z');

/** Strip markup so an assertion reads the page, not the styling. */
const text = (html: string) =>
  html
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#39;|&quot;/g, "'")
    .replace(/\s+/g, ' ')
    .trim();

